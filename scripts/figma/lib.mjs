// Both are PURE functions of their arguments. Do not read the filesystem, the
// clock or the network from here, or the rebuild stops being reproducible.

/**
 * `design/TOKENS.md`, from the same arrays `extract.mjs` writes to
 * `design/tokens.json`. Reproduces the shape of the token tables in
 * `docs/reference/design-system.md` so drift between the two is a plain `diff`.
 */
export function renderTokensTable({ fileKey, lastModified, colors, type, legacy }) {
  return [
    '# Design tokens — generated by `npm run figma:extract`',
    '',
    'Do not hand-edit. Regenerate from the snapshot; if this disagrees with',
    // Points at docs/reference/design-system.md, NOT `CLAUDE.md` §Design
    // System. It said the latter until 2026-08-16, three sessions after the
    // tables moved out of CLAUDE.md — so the committed TOKENS.md (hand-corrected
    // to the new path) and this template disagreed, and the next
    // `npm run figma:extract` would have silently reinstated the dead pointer.
    // Found by `scripts/figma/__tests__/generated-artifacts.test.mjs` on its
    // first run, which is the whole argument for that test.
    '`docs/reference/design-system.md`, this file is right and that one is stale.',
    '',
    `Figma file \`${fileKey}\`, last modified ${lastModified ?? 'unknown'}.`,
    '',
    '**Colors:**',
    '',
    '| Token | Value | n |',
    '|---|---|---|',
    ...colors.map((c) => `| \`${c.name}\` | \`${c.value}\` | ${c.n} |`),
    '',
    '**Type — Poppins:**',
    '',
    '| Token | Size / LH | Weight | n |',
    '|---|---|---|---|',
    ...type.map((t) => `| \`${t.name}\` | ${t.fontSize} / ${t.lineHeight} | ${t.fontWeight} | ${t.n} |`),
    '',
    `**Legacy v1 styles still live inside v2 components: ${legacy.length}.** Do not port these;`,
    'resolve to the v2 token nearest in intent.',
    '',
    '| Token | Value | n |',
    '|---|---|---|',
    ...legacy.map((c) => `| \`${c.name}\` | \`${c.value}\` | ${c.n} |`),
    '',
  ].join('\n')
}

/** `heart-outline` -> `HeartOutline`, giving `<HeartOutlineIcon />`. */
const pascal = (s) =>
  s.split(/[^a-z0-9]+/i).filter(Boolean).map((p) => p[0].toUpperCase() + p.slice(1)).join('')

/**
 * One exported SVG -> the pieces `renderIconModule` needs. `filename` is the
 * `design/icons/` entry (`heart-outline.svg`); `raw` is its contents.
 */
export function svgToIconComponent(filename, raw) {
  const name = filename.replace(/\.svg$/, '')

  const body = raw
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    // Any literal colour becomes the text colour; `fill="none"` is structural and stays.
    .replace(/fill="(?!none")[^"]*"/g, 'fill="currentColor"')
    .replace(/stroke="(?!none")[^"]*"/g, 'stroke="currentColor"')
    // Hyphenated SVG attributes become JSX camelCase. Anchored to attribute
    // position (whitespace before, `=` after) so it can never reach inside a `d`
    // path, where a stray rewrite would silently deform the glyph.
    .replace(/(\s)([a-z]+)-([a-z])([a-z]*=)/g, (_, ws, a, b, rest) => `${ws}${a}${b.toUpperCase()}${rest}`)
    .trim()

  return {
    name: `${pascal(name)}Icon`,
    slug: name,
    viewBox: raw.match(/viewBox="([^"]*)"/)?.[1] ?? '0 0 24 24',
    body,
  }
}

/** `src/components/icons/generated.tsx`, from `svgToIconComponent` output. */
export function renderIconModule(components) {
  return `/*
 * GENERATED by \`npm run figma:components\` from design/icons/*.svg — do not edit.
 *
 * These are the ${components.length} \`Element / Icon / *\` components from Figma
 * \`${FILE_KEY}\`, the set that replaces \`lucide-react\` (decision #4).
 * Every fill is \`currentColor\`, so an icon takes the colour of the text around it;
 * size with \`className\` (\`h-6 w-6\` is the design's 24px default).
 */
import type { SVGProps } from 'react'

export type IconProps = SVGProps<SVGSVGElement>

${components
  .map(
    ({ name, viewBox, body }) => `export function ${name}(props: IconProps) {
  return (
    <svg viewBox="${viewBox}" fill="none" aria-hidden focusable={false} {...props}>
      ${body.split('\n').map((l) => l.trim()).filter(Boolean).join('\n      ')}
    </svg>
  )
}`,
  )
  .join('\n\n')}
`
}
