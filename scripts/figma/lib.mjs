//
// These live here, rather than inline in `extract.mjs` and `components.mjs`,
// for one reason: `scripts/figma/__tests__/generated-artifacts.test.mjs` calls
// them to rebuild `design/TOKENS.md` and `src/components/icons/generated.tsx`
// from the committed sources and byte-compares. A test holding its own copy of
// the template would be a second definition that drifts, and a staleness alarm
// that has drifted from the generator it checks is worse than none — it goes
// green against the wrong artifact.
