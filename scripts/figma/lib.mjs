/**
 * Shared helpers for the Figma snapshot pipeline.
 *
 * The pipeline is split in two on purpose: `pull.mjs` is the only stage that
 * touches the network, and everything downstream is a pure function of the raw
 * JSON it writes. That split is what makes the rate limit survivable — the
 * expensive call happens once a month, and every later question is answered
 * from disk.
 *
 * See design/README.md for the whole rationale.
 */
