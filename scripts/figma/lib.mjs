/**
 * Both roots are overridable so a run can be pointed at a scratch directory —
 * used by the tests, and handy for extracting somewhere else to diff before
 * overwriting the committed snapshot.
 */
const dir = (envVar, fallback) => {
  const override = env[envVar]
  if (!override) return new URL(fallback, import.meta.url)
  return new URL(override.endsWith('/') ? override : `${override}/`, 'file://')
}

